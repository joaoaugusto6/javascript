console.log('Minuto', data.getMinutes());
console.log('Segundo', data.getSeconds());
console.log('MS', data.getMilliseconds());
console.log('Dia semana', data.getDay());// Dom = 0, Seg = 1, Ter = 2, Qua = 3, Qui = 4, Sex = 5, Sáb = 6